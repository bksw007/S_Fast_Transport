const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const context = { exports: {}, Date, Intl, Map, Number };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('apps/web/lib/reports.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, context);
const { deliveryResult, summarizeJobs, filterReportJobs, groupReportJobs, bangkokDate } = context.exports;
const now = Date.parse('2026-09-16T12:00:00+07:00');
const base = { id: '1', workOrder: 'WO-1', jobDate: '2026-09-16', pickupDate: '2026-09-16', deliveryDate: '2026-09-16', deliveryTime: '10:00', customer: 'A', vehiclePlate: 'กข-1', driverName: 'สมชาย', assignedDriverUid: 'driver-1', organizationId: 'main', carrierName: 'Main', status: 'completed', pickupLocation: 'A', deliveryLocation: 'B' };
const onTime = { ...base, arrivedDeliveryAt: '2026-09-16T03:00:00Z' };
const late = { ...base, id: '2', arrivedDeliveryAt: '2026-09-16T03:00:01Z' };
const overdue = { ...base, id: '3', status: 'to_delivery' };
assert.equal(deliveryResult(onTime, now), 'on_time');
assert.equal(deliveryResult(late, now), 'late');
assert.equal(deliveryResult(overdue, now), 'overdue');
assert.equal(deliveryResult({ ...overdue, deliveryTime: '13:00' }, now), 'pending');
assert.equal(deliveryResult(base, now), 'unknown', 'Do not treat completed jobs as on-time without actual arrival');
assert.equal(deliveryResult({ ...overdue, status: 'arrived_delivery' }, now), 'unknown');
assert.equal(deliveryResult({ ...onTime, deliveryTime: '' }, now), 'on_time', 'a delivery on the scheduled day is on time without a specified hour');
assert.equal(deliveryResult({ ...onTime, deliveryTime: '', arrivedDeliveryAt: '2026-09-16T16:59:59Z' }, now), 'on_time', 'Bangkok end of day is included');
assert.equal(deliveryResult({ ...onTime, deliveryTime: '', arrivedDeliveryAt: '2026-09-16T17:00:00Z' }, now), 'late', 'next-day delivery is late');
assert.equal(deliveryResult({ ...overdue, deliveryTime: '' }, now), 'pending', 'date-only jobs remain pending until the end of the scheduled day');
assert.equal(deliveryResult({ ...overdue, deliveryTime: '' }, Date.parse('2026-09-17T00:00:00+07:00')), 'overdue');
assert.equal(deliveryResult({ ...onTime, deliveryTime: '', deliveryDate: '' }, now), 'unknown', 'a missing scheduled date cannot be evaluated');
assert.equal(deliveryResult({ ...onTime, deliveryTime: '25:00' }, now), 'unknown', 'an invalid hour is not treated as date-only');
assert.equal(deliveryResult({ ...late, status: 'cancelled' }, now), 'cancelled');
assert.equal(bangkokDate(new Date('2026-09-15T18:00:00Z')), '2026-09-16');
const jobs = [onTime, late, overdue, { ...base, id: '4' }, { ...late, id: '5', status: 'cancelled' }];
const summary = summarizeJobs(jobs, now);
assert.equal(summary.onTimeRate, 50);
assert.equal(summary.evaluated, 2);
assert.equal(summary.unknown, 1);
assert.equal(summary.overdue, 1);
assert.equal(summary.completed, 3);
assert.equal(summary.trips, 4);
assert.equal(summarizeJobs([{ ...onTime, deliveryTime: '' }], now).onTimeRate, 100, 'date-only on-time jobs count in the reported rate');
assert.equal(summarizeJobs([], now).onTimeRate, null);
const filters = { start: '2026-09-16', end: '2026-09-16', organization: '', customer: '', search: '', status: '' };
assert.equal(filterReportJobs(jobs, filters, now).length, 5);
assert.equal(filterReportJobs(jobs, { ...filters, status: 'delayed' }, now).length, 2);
assert.equal(filterReportJobs(jobs, { ...filters, search: ' กข-1 ' }, now).length, 5);
assert.equal(filterReportJobs(jobs, { ...filters, organization: 'other' }, now).length, 0);
assert.equal(filterReportJobs([{ ...base, jobDate: undefined }], filters, now).length, 1, 'Pickup date is used even without a job date');
assert.equal(filterReportJobs([{ ...base, pickupDate: undefined }], filters, now).length, 0);
assert.equal(filterReportJobs([{ ...base, pickupDate: undefined }], { ...filters, start: '', end: '' }, now).length, 1);
assert.equal(filterReportJobs([{ ...base, id: 'next', jobDate: '2026-09-16', pickupDate: '2026-09-17' }], filters, now).length, 0, 'Tomorrow pickup stays outside today range');
assert.equal(filterReportJobs([{ ...base, id: 'today', jobDate: '2026-09-17' }], filters, now).length, 1, 'Today pickup stays inside range regardless of job date');
const sorted = filterReportJobs([{ ...base, id: 'older', jobDate: '2026-09-18', pickupDate: '2026-09-15' }, { ...base, id: 'newer', jobDate: '2026-09-14' }], { ...filters, start: '', end: '' }, now);
assert.equal(sorted[0].id, 'newer', 'Report order follows pickup date');
assert.equal(groupReportJobs([onTime, { ...late, assignedDriverUid: 'driver-2' }], 'driver', now).length, 2, 'Different drivers with the same name must not merge');
const currentRun = { ...onTime, driverId: 'main-driver-1', assignedDriverUid: 'user-1' };
const historicalRun = { ...late, historical: true, carrierOrganizationId: 'main', driverId: 'main-driver-1', assignedDriverUid: undefined };
assert.equal(groupReportJobs([currentRun, historicalRun], 'driver', now).length, 1, 'Historical and current jobs for the same driver ID merge');
assert.equal(groupReportJobs([currentRun, { ...historicalRun, driverId: 'main-driver-2' }], 'driver', now).length, 2, 'Same-name drivers with different IDs remain separate');
assert.equal(groupReportJobs([onTime, { ...late, organizationId: 'other' }], 'vehicle', now).length, 2, 'Same plate across organizations must not merge');
assert.equal(groupReportJobs(jobs, 'company', now)[0].onTimeRate, 50);
const waiting = { ...base, id: 'partner-waiting', organizationId: 'partner', carrierName: 'Partner', status: 'pending_subcontract', driverName: 'รอมอบหมาย', vehiclePlate: '', assignedDriverUid: undefined };
assert.equal(filterReportJobs([waiting], { ...filters, status: 'pending_subcontract' }, now).length, 1);
assert.equal(groupReportJobs([waiting], 'driver', now)[0].label, 'ยังไม่มอบหมายคนขับ');
assert.equal(groupReportJobs([waiting], 'vehicle', now)[0].label, 'ยังไม่มอบหมายรถ');
assert.equal(summarizeJobs([waiting], now).active, 1);
console.log('PASS: report dates, Bangkok timezone, punctuality, missing data, cancellations, filters, groups and denominators');
